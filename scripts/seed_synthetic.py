"""Seed a running WIREFRAME server with SYNTHETIC poles for UI development.

    python -m scripts.seed_synthetic --url http://127.0.0.1:8000 --n 8

Every pole code starts with ``SYN-`` and every image is generated by
app/devtools/synthetic.py with reference polygon labels (segmentation source
"annotation"). These are not field observations.
"""

from __future__ import annotations

import argparse
import io

import httpx
from PIL import Image

from app.devtools.synthetic import make_scene

# Points around Dasmarinas, Cavite (study area province, Section 3.4.7); illustrative only.
ANCHOR = (14.3294, 120.9367)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", default="http://127.0.0.1:8000")
    ap.add_argument("--n", type=int, default=8)
    args = ap.parse_args()
    with httpx.Client(base_url=args.url, timeout=60) as c:
        for i in range(args.n):
            sc = make_scene(seed=100 + i, sag_scale=0.35 + 0.13 * i, clutter=3 + 2 * i)
            buf = io.BytesIO()
            Image.fromarray(sc.rgb).save(buf, "JPEG", quality=90)
            lat = ANCHOR[0] + 0.0042 * ((i * 37) % 7 - 3)
            lon = ANCHOR[1] + 0.0047 * ((i * 53) % 9 - 4)
            r = c.post("/api/analysis/upload",
                       files={"file": (f"synthetic_{i:02d}.jpg", buf.getvalue(), "image/jpeg"),
                              "labels": (f"synthetic_{i:02d}.txt", sc.labels.encode(), "text/plain")},
                       data={"pole_code": f"SYN-{i + 1:03d}", "barangay": "Synthetic (demo)",
                             "latitude": f"{lat:.6f}", "longitude": f"{lon:.6f}",
                             **({"span_m": "38", "temperature_c": "33"} if i % 2 else {})})
            r.raise_for_status()
            print(r.json()["id"], f"SYN-{i + 1:03d}")


if __name__ == "__main__":
    main()
